type LocaleContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey) => string;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);
const localeChangeEvent = "aster-locale-change";

function isLocale(value: string): value is Locale {
  return supportedLocales.includes(value as Locale);
}

function subscribeToLocaleChanges(onStoreChange: () => void) {
  window.addEventListener("storage", onStoreChange);
  window.addEventListener(localeChangeEvent, onStoreChange);
  return () => {
    window.removeEventListener("storage", onStoreChange);
    window.removeEventListener(localeChangeEvent, onStoreChange);
  };
}

function getLocaleSnapshot(): Locale {
  const savedLocale = window.localStorage.getItem("aster-locale");
  return savedLocale && isLocale(savedLocale) ? savedLocale : "en";
}

function getServerLocaleSnapshot(): Locale {
  return "en";
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const locale = useSyncExternalStore(subscribeToLocaleChanges, getLocaleSnapshot, getServerLocaleSnapshot);

  function setLocale(nextLocale: Locale) {
    window.localStorage.setItem("aster-locale", nextLocale);
    window.dispatchEvent(new Event(localeChangeEvent));
    document.documentElement.lang = nextLocale;
  }

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<LocaleContextValue>(() => ({
    locale,
    setLocale,
    t: (key) => messages[locale][key] ?? messages.en[key],
  }), [locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("useLocale must be used within LocaleProvider.");
  return value;
}

export function LanguageSelect() {
  const { locale, setLocale, t } = useLocale();

  return (
    <label className="language-select">
      <span>{t("language")}</span>
      <select
        aria-label={t("language")}
        value={locale}
        onChange={(event) => {
          if (isLocale(event.currentTarget.value)) setLocale(event.currentTarget.value);
        }}
      >
        {supportedLocales.map((supportedLocale) => (
          <option key={supportedLocale} value={supportedLocale}>
            {localeLabels[supportedLocale]}
          </option>
        ))}
      </select>
    </label>
  );
}

export function localizedLanguage(locale: Locale) {
  return localeLabels[locale];
}
